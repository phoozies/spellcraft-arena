# Regenerates the human- and AI-readable spell registry from the code:
#
#   python tools/gen-spell-registry.py
#
# Reads src/shared/Spells/SpellDefinitions.luau (name, element, slot, role,
# archetype, sfx cues, model) and src/shared/Spells/SpellRegistry.luau (particle
# style, cast pose, Fx events, notes), then writes
#   docs/semantic/spell_registry.yaml          machine-readable, one record per spell
#   the table between the REGISTRY markers in docs/SPELLS.md
#
# tests/Registry.spec.luau is what enforces the registry in code; this script
# keeps the docs from drifting from it. Pure Python, no packages needed.

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf8") as handle:
        return handle.read()


def definitions():
    text = read("src/shared/Spells/SpellDefinitions.luau")
    rows = []
    # Each spell is a table starting at `id = "X",` and ending at the next one.
    starts = [m.start() for m in re.finditer(r'\n\t\t\tid = "|\n\t\tid = "', text)]
    ids = [m for m in re.finditer(r'\n\t\tid = "(\w+)",', text)]
    for index, match in enumerate(ids):
        end = ids[index + 1].start() if index + 1 < len(ids) else len(text)
        block = text[match.start():end]

        def grab(pattern, default=None):
            found = re.search(pattern, block)
            return found.group(1) if found else default

        rows.append({
            "id": match.group(1),
            "name": grab(r'name = "([^"]+)"'),
            "element": grab(r'element = "(\w+)"'),
            "slot": int(grab(r"slot = (\d)")),
            "rarity": grab(r'rarity = "(\w+)"'),
            "role": grab(r'role = "(\w+)"'),
            "archetype": grab(r'archetype = "(\w+)"'),
            "cast": grab(r'cast = "(\w+)"'),
            "impact": grab(r'impact = "(\w+)"'),
            "model": grab(r'\n\t\t\tmodel = "(\w+)"') or grab(r'\n\t\t\t\tmodel = "(\w+)"'),
            "cooldown": grab(r"cooldown = ([\d.]+)"),
        })
    return rows


def registry():
    text = read("src/shared/Spells/SpellRegistry.luau")
    body = text[text.index("local ENTRIES"):text.index("SpellRegistry.entries")]
    entries = {}
    for match in re.finditer(r"\n\t(\w+) = \{\n(.*?)\n\t\},", body, re.S):
        block = match.group(2)
        entries[match.group(1)] = {
            "vfx": re.search(r'vfx = "(\w+)"', block).group(1),
            "fx": re.findall(r'"(\w+)"', re.search(r"fx = \{([^}]*)\}", block).group(1)),
            "animation": re.search(r'animation = "(\w+)"', block).group(1),
            "no_impact": "noImpact = true" in block,
            "note": re.search(r'note = "([^"]+)"', block).group(1),
        }
    return entries


def yaml_text(rows, entries):
    out = [
        "# Spell registry: the presentation of every spell (model, particle style, cast",
        "# animation, sounds). GENERATED by tools/gen-spell-registry.py from",
        "# src/shared/Spells/SpellDefinitions.luau and SpellRegistry.luau; edit those and",
        "# rerun the script. tests/Registry.spec.luau enforces it in code.",
        "#",
        "# model      3D model: a block model built by ModelKit from Models/BlockModels (Blender",
        "#            source tools/blender/block_models.py, FBX in assets/models/blocks), or an",
        "#            imported mesh stored in the place (Fireball, WaterBubble, RockWall, Gust, Zap,",
        "#            Heal, BlackHole, Turret)",
        "# vfx        key into Spells/VfxStyles (bolt trail + impact burst; buffs also an aura)",
        "# fx         the Fx remote events the spell triggers on clients (FxController)",
        "# animation  key into Spells/CastPoses (the cast pose, played by Fx/CastAnimations)",
        "# sfx        cue names in Audio/Cues; impact null = a buff or wall with nothing to hit",
        "",
        "spells:",
    ]
    for row in rows:
        entry = entries[row["id"]]
        out.append(f"  - id: {row['id']}")
        out.append(f"    name: {row['name']}")
        out.append(f"    element: {row['element']}")
        out.append(f"    slot: {row['slot']}")
        out.append(f"    rarity: {row['rarity'] if row['rarity'] else 'base'}")
        out.append(f"    role: {row['role']}")
        out.append(f"    archetype: {row['archetype']}")
        out.append(f"    cooldown: {row['cooldown']}")
        out.append(f"    model: {row['model']}")
        out.append(f"    vfx: {entry['vfx']}")
        out.append("    fx: [" + ", ".join(entry["fx"]) + "]")
        out.append(f"    animation: {entry['animation']}")
        out.append("    sfx:")
        out.append(f"      cast: {row['cast']}")
        out.append(f"      impact: {row['impact'] if row['impact'] else 'null'}")
        out.append(f'    note: "{entry["note"]}"')
    return "\n".join(out) + "\n"


def table_text(rows, entries):
    lines = [
        "| Spell | School | Rarity | Model | Particles (`VfxStyles`) | Cast pose (`CastPoses`) | Cast sound | Impact sound |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        entry = entries[row["id"]]
        impact = row["impact"] or "n/a"
        lines.append(
            f"| **{row['name']}** | {row['element']} | {row['rarity'] or 'base'} | `{row['model']}` | `{entry['vfx']}` | "
            f"{entry['animation']} | `{row['cast']}` | {'`' + impact + '`' if row['impact'] else impact} |"
        )
    return "\n".join(lines)


def main():
    rows, entries = definitions(), registry()
    missing = [row["id"] for row in rows if row["id"] not in entries]
    if missing or len(rows) != len(entries):
        sys.exit(f"registry and definitions disagree: missing {missing}")
    for row in rows:
        if not row["model"]:
            sys.exit(f"{row['id']} has no model")

    with open(os.path.join(ROOT, "docs", "semantic", "spell_registry.yaml"), "w", encoding="utf8", newline="\n") as handle:
        handle.write(yaml_text(rows, entries))

    path = os.path.join(ROOT, "docs", "SPELLS.md")
    text = read("docs/SPELLS.md")
    start, end = "<!-- REGISTRY:start -->", "<!-- REGISTRY:end -->"
    if start in text and end in text:
        before, rest = text.split(start, 1)
        _, after = rest.split(end, 1)
        text = before + start + "\n" + table_text(rows, entries) + "\n" + end + after
        with open(path, "w", encoding="utf8", newline="\n") as handle:
            handle.write(text)
    print(f"wrote spell_registry.yaml and the SPELLS.md table ({len(rows)} spells)")


if __name__ == "__main__":
    main()
